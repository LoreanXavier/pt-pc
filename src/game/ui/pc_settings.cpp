std::vector<std::string_view> PcDescriptionKeys() {
    std::vector<std::string_view> keys;
    for (const Entry& entry : kTexts) if (entry.key.find("note") != std::string_view::npos || entry.key == "pc_mic_say_jack") keys.push_back(entry.key);
    return keys;
}

std::string PcNoteText(std::string_view note, int language) {
    const size_t split = note.find(kPcNoteArgument);
    if (split == std::string_view::npos) return std::string(PcText(note, language));
    std::string text(PcText(note.substr(0, split), language));
    std::string_view rest = note.substr(split + 1);
    for (int n = 1; ; ++n) {
        const size_t end = rest.find(kPcNoteArgument);
        const std::string token = "{" + std::to_string(n) + "}";
        if (const size_t at = text.find(token); at != std::string::npos) text.replace(at, token.size(), rest.substr(0, end));
        if (end == std::string_view::npos) break;
        rest = rest.substr(end + 1);
    }
    return text;
}

std::string_view PcText(std::string_view key, int language) {
    if (language >= 1) {
        const auto text = localized::Menu(key, language);
        if (!text.empty()) return text;
    }
    for (const Entry& e : kTexts) {
        if (e.key == key) {
            const std::string_view text = language > 0 && language < kLanguages ? e.text[language] : std::string_view();
            return text.empty() ? e.text[0] : text;
        }
    }
    return key;
}

